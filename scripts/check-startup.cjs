'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html','utf8');
const start = html.indexOf('      function createStartupGuard(');
const end = html.indexOf('      async function init()', start);
assert.ok(start >= 0 && end > start);
const fields = Object.fromEntries(['edition','mainColor','subColor','supplement','series','stage'].map(id => [id,{ value: '' }]));
const listeners = new Map();
const panel = { addEventListener(name, cb) { listeners.set(name,cb); }, removeEventListener(name) { listeners.delete(name); } };
const master = { edition: 'JBS 第33期', color: '#6B0D2F', subColor: '#9A5A72' };
let footerUpdates = 0;
const api = Function('$','findTournamentForCurrentFields','makeSubColor','restoreAutoSupplement','syncSupplementFromSelections','populate','render',
  html.slice(start,end) + '\nreturn {createStartupGuard, refreshStartupBrand};')(
  id => fields[id], () => master, () => master.subColor, () => footerUpdates++, () => footerUpdates++, () => {}, () => {});
const guard = api.createStartupGuard(panel);
fields.series.value = '盤聖戦';
fields.stage.value = '３回戦';
fields.edition.value = '手入力';
fields.mainColor.value = '#123456';
fields.supplement.value = '独自フッター';
for (const id of ['series','stage','edition','mainColor','supplement']) listeners.get('input')({ target: { id } });
api.refreshStartupBrand(null, guard);
assert.equal(fields.series.value, '盤聖戦');
assert.equal(fields.stage.value, '３回戦');
assert.equal(fields.edition.value, '手入力');
assert.equal(fields.mainColor.value, '#123456');
assert.equal(fields.supplement.value, '独自フッター');
assert.equal(footerUpdates, 0);
guard.stop();
const fresh = api.createStartupGuard(panel);
fields.edition.value = '';
api.refreshStartupBrand(null, fresh);
assert.equal(fields.edition.value, master.edition);
assert.equal(fields.mainColor.value, master.color);
assert.equal(fields.stage.value, '３回戦');
assert.equal(footerUpdates, 1);
fresh.stop();
assert.ok(html.includes('if (!canRestore(side)) return;'));
assert.ok(html.includes('await JBSMembers.load({ cacheKey })'));
assert.ok(!html.includes('ROMAJI_TO_HIRAGANA'));
console.log('Thumbnail startup edits and shared member processing checks passed.');
